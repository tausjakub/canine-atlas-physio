import fs from 'node:fs';
const root=new URL('../',import.meta.url),file=new URL('app/globals.css',root);
const themes=JSON.parse(fs.readFileSync(new URL('app/themes.json',root),'utf8'));
const colors=new Set();
const source=fs.readFileSync(file,'utf8').replace(/var\(--tone-([a-f\d]+),\s*#[a-f\d]+\)|#([a-f\d]{8}|[a-f\d]{6}|[a-f\d]{4}|[a-f\d]{3})\b/gi,(match,existing,hex)=>{hex=(existing||hex).toLowerCase();colors.add(hex);return existing?match:`var(--tone-${hex}, #${hex})`;});
fs.writeFileSync(file,source);
const rgb=hex=>hex.match(/\w\w/g).map(v=>parseInt(v,16));
function mapped(hex,t){
 if(hex.length<=4)hex=[...hex].map(c=>c+c).join('');
 const [r,g,b]=rgb(hex.slice(0,6)),max=Math.max(r,g,b),min=Math.min(r,g,b),light=(max+min)/510,sat=max-min;
 let color=light<.09?t.base:light<.28?t.surface:light<.48?t.border:light<.67?t.muted:t.text;
 if(light>=.48&&sat>55)color=r>g*1.25&&r>b*1.2?t.error:t.accent;
 return color+(hex.length===8?hex.slice(6):'');
}
let css='/* Generated by scripts/generate-themes.mjs. Original dark colors remain the fallbacks. */\n';
for(const t of themes){css+=`html[data-theme="${t.id}"]{color-scheme:${t.scheme};--theme-base:${t.base};--theme-surface:${t.surface};--theme-text:${t.text};--theme-muted:${t.muted};--theme-border:${t.border};--theme-accent:${t.accent};--answer-bg:${t.answer};--answer-text:${t.answerText};`;
 if(t.id!=='dark')for(const c of [...colors].sort())css+=`--tone-${c}:${mapped(c,t)};`;
 css+='}\n';}
fs.writeFileSync(new URL('app/theme-palette.css',root),css);
